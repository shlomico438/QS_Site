def get_resource_page(slug: str | None) -> dict[str, Any] | None:
    key = (slug or "").strip().strip("/")
    if key not in RESOURCES_PAGES:
        return None
    page = dict(RESOURCES_PAGES[key])
    # Same hub list everywhere: every other published cluster page (pillar included on children).
    related_pages = []
    for rel in RESOURCE_SLUGS_PUBLISHED:
        if rel == key:
            continue
        other = RESOURCES_PAGES.get(rel)
        if other:
            related_pages.append(
                {
                    "path": other["path"],
                    "label": other["nav_label"],
                    "h1": other["h1"],
                }
            )
    page["related_pages"] = related_pages
    return page
